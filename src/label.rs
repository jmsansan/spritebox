//! A built-in 3×5 pixel font for the labels of preview sheets. Lowercase letters are
//! drawn as uppercase; characters it lacks are drawn as `?`.

use crate::{Color, Image};

/// Width of a glyph, and the advance with the space after it.
pub(crate) const GLYPH_WIDTH: u32 = 3;
pub(crate) const ADVANCE: u32 = 4;
pub(crate) const HEIGHT: u32 = 5;

